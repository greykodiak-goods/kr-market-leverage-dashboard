/** 목록이 덮는 연도(오름차순). */
export const PIT_YEARS: number[] = Object.keys(PIT1010)
  .map(Number)
  .sort((a, b) => a - b)

/** 그 해의 유니버스 코드(코스피 10 + 코스닥 10). 목록에 없는 해는 빈 배열. */
export function pitCodes(year: number): string[] {
  const y = PIT1010[year]
  return y ? [...y.ks, ...y.kq] : []
}

/** 전 연도 합집합 — 시세를 한 번만 받아 모든 해가 나눠 쓰기 위한 로딩 목록(중복 제거·정렬). */
export const PIT_UNION: string[] = (() => {
  const set = new Set<string>()
  for (const y of PIT_YEARS) for (const code of pitCodes(y)) set.add(code)
  return [...set].sort()
})()

